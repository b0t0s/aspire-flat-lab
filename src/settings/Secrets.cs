using System.Security.Cryptography;
using static EnvironmentSettings;

internal sealed class LabSecrets(IDistributedApplicationBuilder builder)
{
    private readonly string envFile = Path.Combine(builder.AppHostDirectory, ".env");
    private readonly Dictionary<string, IResourceBuilder<ParameterResource>> parameters = new(StringComparer.Ordinal);

    public IResourceBuilder<ParameterResource> Get(string key, SecretKind kind = SecretKind.Password, string? legacyFile = null, params string[] aliases)
    {
        if (parameters.TryGetValue(key, out var existing))
        {
            return existing;
        }

        var name = key.ToLowerInvariant().Replace('_', '-');
        var value = Read(key);
        if (value is null)
        {
            value = aliases.Select(Read).FirstOrDefault(v => v is not null)
                ?? ReadLegacyFile(legacyFile)
                ?? (kind != SecretKind.Manual && builder.ExecutionContext.IsRunMode ? Generate(kind) : null);
            if (value is not null && builder.ExecutionContext.IsRunMode)
            {
                Persist(key, value);
            }
        }

        if (value is not null)
        {
            builder.Configuration[$"Parameters:{name}"] = value;
        }

        var parameter = builder.AddParameter(name, secret: true)
            .WithDescription(kind == SecretKind.Manual ? $".env `{key}` (required, set manually)" : $".env `{key}`");
        parameters.Add(key, parameter);
        return parameter;
    }

    private string? Read(string key)
    {
        return builder.Configuration[key] is { Length: > 0 } value ? value : null;
    }

    private static string? ReadLegacyFile(string? path)
    {
        if (path is null || !File.Exists(path))
        {
            return null;
        }
        try
        {
            return File.ReadAllText(path).Trim() is { Length: > 0 } value ? value : null;
        }
        catch (UnauthorizedAccessException)
        {
            return null;
        }
        catch (IOException)
        {
            return null;
        }
    }

    private void Persist(string key, string value)
    {
        var lines = File.Exists(envFile) ? File.ReadAllLines(envFile).ToList() : [];
        var empty = lines.FindIndex(line => line.Trim() == $"{key}=");
        if (empty >= 0)
        {
            lines[empty] = $"{key}={value}";
        }
        else
        {
            if (!lines.Contains(GeneratedHeader)) lines.AddRange(["", GeneratedHeader]);
            lines.Add($"{key}={value}");
        }
        File.WriteAllText(envFile, string.Join('\n', lines) + "\n");
    }

    private const string GeneratedHeader = "## ===== Generated by apphost on first run (move into the right section if you like) =====";

    private static string Generate(SecretKind kind)
    {
        return kind switch
        {
            SecretKind.Password => RandomAlphanumeric(32),
            SecretKind.LongPassword => RandomAlphanumeric(64),
            SecretKind.Hex32 => Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(32)),
            SecretKind.Hex16 => Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(16)),
            SecretKind.Base64 => Convert.ToBase64String(RandomNumberGenerator.GetBytes(48)),
            SecretKind.LaravelKey => "base64:" + Convert.ToBase64String(RandomNumberGenerator.GetBytes(32)),
            _ => throw new ArgumentOutOfRangeException(nameof(kind)),
        };
    }

    private static string RandomAlphanumeric(int length)
    {
        return RandomNumberGenerator.GetString("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789", length);
    }
}
